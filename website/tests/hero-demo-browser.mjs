import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';

const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROME_PATH });
const origin = process.env.DEMO_ORIGIN ?? 'http://localhost:3310';
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
page.on('pageerror', e => errors.push(e.message));
const card = page.locator('.hero-demo');
const next = async (count = 1) => {
  for (let i = 0; i < count; i++) await card.getByRole('button', { name: 'Advance demo one step' }).click();
};
try {
  await page.goto(origin);
  await card.getByRole('combobox').waitFor();
  await page.waitForTimeout(2800);
  assert.equal(await card.locator('.hd-sequence > span').textContent(), '1/10');
  assert.equal(await page.locator('#content .decision-console').count(), 0);
  assert.equal(await card.locator('.hd-server').count(), 5);
  assert.ok((await card.boundingBox()).height < 490);
  assert.ok((await card.boundingBox()).width < 600);
  await next(3);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'CHALLENGE');
  await page.screenshot({ path: '/tmp/agentaction-hero-desktop.png' });
  await next(3);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'ALLOW');
  await next();
  assert.match(await card.locator('.hd-boundary').textContent(), /Internal identifiers removed/);
  await next();
  assert.equal(await card.locator('.hd-verdict').textContent(), 'DENY');
  await card.locator('.hd-trace-step').nth(3).click();
  assert.equal(await card.locator('.hd-verdict').textContent(), 'CHALLENGE');
  assert.equal(await card.locator('.hd-sequence > span').textContent(), '4/10');
  await card.getByRole('combobox').selectOption('history');
  await next(6);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'CHALLENGE');
  assert.match(await card.locator('.hd-history').textContent(), /3 recent claims/);
  await next(2);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'ALLOW');
  await card.getByRole('combobox').selectOption('expired');
  await next(6);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'CHALLENGE');
  assert.equal(await card.locator('.hd-fact.stale').count(), 1);
  await card.getByRole('combobox').selectOption('refunded');
  await next(3);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'DENY');
  await card.getByRole('combobox').selectOption('mismatch');
  await next(6);
  assert.equal(await card.locator('.hd-verdict').textContent(), 'DENY');
  await next(3);
  assert.equal(await card.getByRole('button', { name: 'Advance demo one step' }).isDisabled(), true);
  await card.getByRole('button', { name: 'Replay', exact: false }).click();
  await card.getByRole('button', { name: 'Pause', exact: false }).click();
  assert.equal(await card.locator('.hd-sequence > span').textContent(), '1/10');
  await card.getByRole('button', { name: 'Reset hero demo' }).click();
  assert.equal(await card.locator('.hd-sequence > span').textContent(), '1/10');
  await card.getByRole('button', { name: 'Play', exact: false }).click();
  await page.waitForTimeout(2800);
  await card.getByRole('button', { name: 'Pause', exact: false }).click();
  const paused = await card.locator('.hd-sequence > span').textContent();
  await page.waitForTimeout(2800);
  assert.equal(await card.locator('.hd-sequence > span').textContent(), paused);
  assert.equal(page.url(), `${origin}/`);
  await page.setViewportSize({ width: 390, height: 844 });
  await card.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.ok((await card.boundingBox()).height < 510);
  await card.screenshot({ path: '/tmp/agentaction-hero-mobile.png' });
  assert.deepEqual(errors, []);

  const auto = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  await auto.goto(origin);
  await auto.locator('.hero-demo .hd-controls').waitFor();
  await auto.waitForTimeout(2800);
  assert.notEqual(await auto.locator('.hd-sequence > span').textContent(), '1/10');
  await auto.locator('footer').scrollIntoViewIfNeeded();
  await auto.waitForTimeout(200);
  const offscreen = await auto.locator('.hd-sequence > span').textContent();
  await auto.waitForTimeout(2800);
  assert.equal(await auto.locator('.hd-sequence > span').textContent(), offscreen);
  console.log('PASS: compact native hero, all scenarios, sanitization, controls, reduced motion, visible autoplay/offscreen pause, desktop/mobile layout and no navigation.');
} finally { await browser.close(); }
